import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const analyticsDirectory = path.resolve(scriptDirectory, "..");
const outputDirectory = path.join(analyticsDirectory, "generated");

const orderedFiles = [
  "sql/staging/refresh_stg_ga4_events.sql",
  "sql/intermediate/refresh_int_ga4_sessions.sql",
  "sql/dimensions/refresh_dim_page.sql",
  "sql/facts/refresh_fct_daily_site.sql",
  "sql/facts/refresh_fct_daily_page.sql",
  "sql/facts/refresh_fct_traffic_acquisition.sql"
];

const sections = [];
for (const relativePath of orderedFiles) {
  const sql = (await fs.readFile(path.join(analyticsDirectory, relativePath), "utf8")).trim();
  sections.push([
    `-- BEGIN ${relativePath}`,
    "BEGIN",
    sql,
    "END;",
    `-- END ${relativePath}`
  ].join("\n"));
}

const header = [
  "-- Generated by analytics/scripts/build-scheduled-query.mjs.",
  "-- Do not edit this output directly; edit the source model SQL files.",
  "-- Schedule daily at 20:07 UTC with failure email notifications enabled.",
  "-- BigQuery location: US.",
  ""
].join("\n");

await fs.mkdir(outputDirectory, { recursive: true });
const outputPath = path.join(outputDirectory, "refresh_semantic_layer.sql");
await fs.writeFile(outputPath, `${header}${sections.join("\n\n")}\n`, "utf8");

process.stdout.write(`${JSON.stringify({
  output: path.relative(path.resolve(analyticsDirectory, ".."), outputPath),
  model_count: orderedFiles.length,
  models: orderedFiles
}, null, 2)}\n`);
